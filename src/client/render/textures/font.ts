export function drawFont(): { canvas: HTMLCanvasElement; charsPerRow: number } {
  const charsPerRow = 16;
  const rows = Math.ceil(FONT_CHARS.length / charsPerRow);
  const c = makeCanvas(charsPerRow * FONT_W, rows * FONT_H);
  for (let i = 0; i < FONT_CHARS.length; i++) {
    const g = G[FONT_CHARS[i]];
    if (!g) continue;
    const ox = (i % charsPerRow) * FONT_W;
    const oy = Math.floor(i / charsPerRow) * FONT_H;
    g.split(' ').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '1') px(c, ox + x, oy + y, '#ffffff');
    });
  }
  return { canvas: c.canvas, charsPerRow };
}
